import pytest


from app.main import check_password


@pytest.mark.parametrize("fake_password, validity_bool", [
    pytest.param("",
                 False,
                 id="No empty string."),
    pytest.param(" ",
                 False,
                 id="Not single space."),
    pytest.param("00000000",
                 False,
                 id="Not only zeros."),
    pytest.param("1234567890",
                 False,
                 id="Not only numbers."),
    pytest.param("        ",
                 False,
                 id="Not only spaces."),
    pytest.param("ABCDEFGH",
                 False,
                 id="Not only uppercase."),
    pytest.param("abcdefgh",
                 False,
                 id="Not only lowercase."),
    pytest.param("________",
                 False,
                 id="Not only underscores."),
    pytest.param("Aa_0",
                 False,
                 id="At least eight characters."),
    pytest.param("_Psw0rd_",
                 True,
                 id="_Psw0rd_ characters."),
    pytest.param("_PSW0RD_",
                 True,
                 id="_PSW0RD_ characters."),
    pytest.param("_PSW0RD_90123456",
                 True,
                 id="_PSW0RD_90123456 string."),
    pytest.param("_PSW0RD_901234567",
                 False,
                 id="_PSW0RD_901234567 too long."),
    pytest.param("00000OO_",
                 True,
                 id="00000OO_ shall be considered valid."),
    pytest.param("ò00000O_",
                 False,
                 id="Invalid accent."),
    pytest.param("Password_",
                 False,
                 id="Password need a number."),
    pytest.param("NewPassword0",
                 False,
                 id="Password need a special character."),
    pytest.param("New Password0",
                 False,
                 id="Space not allowed."),
    pytest.param("New_Password0",
                 True,
                 id="Correct password."),
    pytest.param("0New_Password0",
                 True,
                 id="Correct password."),
    pytest.param("0new_password0",
                 False,
                 id="Password need uppercase."),
    pytest.param("0_QqWwEeRrTtYyUu",
                 True,
                 id="Testing first characters."),
    pytest.param("1$IiOoPpAaSsDdFf",
                 True,
                 id="Testing second set of characters"),
    pytest.param("2@GgHhJjKkLlZzXx",
                 True,
                 id="Testing third set of characters"),
    pytest.param("3#CcVvBbNnMm4567",
                 True,
                 id="Testing fourth set of characters"),
    pytest.param("89&-!ASD",
                 True,
                 id="Testing fifth set of characters"),
])
def test_check_password(fake_password: str,
                        validity_bool: bool) -> None:
    assert check_password(fake_password) == validity_bool
